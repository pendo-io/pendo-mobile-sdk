find_csproj_files() {
  find . \
    \( -path '*/bin' -o -path '*/obj' -o -path '*/node_modules' -o -path '*/.git' \) -prune \
    -o -iname '*.csproj' -print 2>/dev/null
}

declares_maui() {
  grep -qi '<UseMaui>[[:space:]]*true[[:space:]]*</UseMaui>' "$1" 2>/dev/null
}

# Matches Exe and WinExe, and tolerates the per-TFM Condition the MAUI
# template puts on this element.
declares_executable_output() {
  grep -qiE '<OutputType[^>]*>[[:space:]]*(Win)?Exe[[:space:]]*</OutputType>' "$1" 2>/dev/null
}

# The application head. Both markers are required because the MAUI class
# library template also sets UseMaui, which would otherwise make the head
# whichever .csproj `find` happened to return first.
find_maui_head_project() {
  find_csproj_files |
    while IFS= read -r proj; do
      declares_maui "$proj" && declares_executable_output "$proj" || continue
      printf '%s\n' "$proj"
      break
    done
}

msbuild_property() {
  dotnet msbuild "$1" -getProperty:"$2" 2>/dev/null
}

# `dotnet build -f` rejects any TFM the project does not declare (NETSDK1005),
# so this is read rather than assumed. MSBuild evaluation is preferred over the
# raw XML because it resolves conditions and Directory.Build.props.
maui_android_tfm() {
  local proj="$1" declared

  declared=$(msbuild_property "$proj" TargetFrameworks)
  [ -n "$declared" ] || declared=$(msbuild_property "$proj" TargetFramework)
  [ -n "$declared" ] || declared=$(cat "$proj" 2>/dev/null)

  printf '%s\n' "$declared" | tr ';' '\n' |
    grep -oE 'net[0-9]+\.[0-9]+-android[0-9.]*' | head -n 1
}

maui_build() {
  local proj tfm

  if ! command -v dotnet >/dev/null 2>&1; then
    err "dotnet is not installed"
    return 2
  fi

  proj=$(find_maui_head_project)
  if [ -z "$proj" ]; then
    err "no MAUI application head found (need a .csproj with both <UseMaui>true</UseMaui> and an executable <OutputType>)"
    return 2
  fi

  tfm=$(maui_android_tfm "$proj")
  if [ -z "$tfm" ]; then
    err "\"${proj}\" declares no Android target framework — this script verifies MAUI's Android head only"
    return 2
  fi

  attributed_step "MAUI" "dotnet restore \"${proj}\"" \
    dotnet restore "$proj" || return $?

  log "verifying the Android head only (${tfm}) — it needs no Xcode and no code signing; MAUI's iOS, MacCatalyst and Windows heads are not verified here"
  attributed_step "MAUI Android" "dotnet build \"${proj}\" -f ${tfm}" \
    dotnet build "$proj" -f "$tfm" -c Debug
}

