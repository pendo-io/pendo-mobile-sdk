# Assert the working-directory contract before anything runs, so a monorepo
# git root is told where the app is instead of being handed a bare "nothing
# could be verified". Opts out for ios/maui and for an unknown platform,
# which the case below still reports as usage error 1.
require_buildable_cwd
status=$?

if [ "$status" -eq 0 ]; then
  case "$PLATFORM" in
    ios)          ios_head "."; status=$? ;;
    android)      android_build; status=$? ;;
    react-native) cross_platform_js_build "react-native"; status=$? ;;
    expo)         cross_platform_js_build "expo"; status=$? ;;
    flutter)      flutter_build; status=$? ;;
    maui)         maui_build; status=$? ;;
    *)
      err "unknown platform: ${PLATFORM}"
      usage
      status=1
      ;;
  esac
fi

case "$status" in
  0) log "BUILD PASSED (${PLATFORM})" ;;
  2) log "BUILD NOT VERIFIED (${PLATFORM}) — see the detail above (required toolchain absent, wrong working directory, or a failure that could not be attributed to this install)" ;;
  *) err "BUILD FAILED (${PLATFORM})" ;;
esac

exit "$status"
